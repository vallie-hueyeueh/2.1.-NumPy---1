import pandas as pd
import matplotlib.pyplot as plt
import warnings
warnings.filterwarnings('ignore')  # Убираем технические предупреждения

# Предобработка и разбивка данных
from sklearn.model_selection import train_test_split

# Метрики оценки модели
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    ConfusionMatrixDisplay
)

#
#  ПРОЕКТ 1: ФИЛЬТРАЦИЯ СПАМА
# ===========================================================================
section("ПРОЕКТ 1: ФИЛЬТРАЦИЯ СПАМА — SMS SPAM DETECTION")

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 1.1 — ЗАГРУЗКА ДАННЫХ
# spam.csv: два столбца — Category (ham/spam) и Message (текст сообщения).
# 5572 SMS. Настоящий датасет UCI/Kaggle SMS Spam Collection.
# ────────────────────────────────────────────────────────────────────────────
print("\n spam.csv...")
data = pd.read_csv("spam.csv")
print(data.head())
print("\nСтолбцы:", data.columns.tolist())

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 1.2 — АНАЛИЗ ДАННЫХ
# Сколько спама и нормальных сообщений
# ────────────────────────────────────────────────────────────────────────────
print("\n Распределение классов:")
print(data["Category"].value_counts())
print(f"\n  ham  (нормальные): {(data['Category']=='ham').sum()}")
print(f"  spam (спам):        {(data['Category']=='spam').sum()}")

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 1.3 — ВЕКТОРИЗАЦИЯ (ЗАЧЕМ ЭТО НУЖНО)
# ────────────────────────────────────────────────────────────────────────────

 # ВЕКТОРИЗАЦИЯ ТЕКСТА (объяснение):
 # Алгоритмы МО понимают только числа, не текст.
 # Нужно превратить каждое SMS в вектор чисел.
 # CountVectorizer строит матрицу "мешка слов" (Bag of Words):
 #  Столбцы = все уникальные слова в датасете (словарь)
 #  Строки  = тексты сообщений
 #  Ячейка  = сколько раз это слово встречается в этом тексте

#  Пример для 3 SMS:
#    "Win the lottery"      → [0, 0, 1, 1, 1, 0, ...]
#    "Hi how are you"       → [1, 1, 0, 0, 0, 1, ...]
#    "Free lottery tickets" → [0, 0, 1, 0, 1, 0, ...]

#  Очистка (что обычно делают перед векторизацией):
#    - Строчные буквы (lower case)
#    - Удаление знаков препинания
#    - Удаление стоп-слов ('the', 'is', 'a'...)
#  CountVectorizer делает это частично автоматически.


# ────────────────────────────────────────────────────────────────────────────
# ШАГ 1.4 — КОДИРОВКА МЕТОК
# ────────────────────────────────────────────────────────────────────────────
# Преобразуем "ham" → 0, "spam" → 1
# Это нужно для некоторых метрик, хотя Pipeline работает и со строками
data["Spam"] = data["Category"].map({"ham": 0, "spam": 1})

print(" Проверяем новый столбец Spam:")
print(data[["Category", "Spam"]].head(8))
print("\nКолонки датафрейма:", data.columns.tolist())

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 1.5 — ПРИМЕР РАБОТЫ CountVectorizer
# что делает векторизатор изнутри
# ────────────────────────────────────────────────────────────────────────────
from sklearn.feature_extraction.text import CountVectorizer

print("\n Пример работы CountVectorizer на 4 SMS:")
example_texts = [
    "Win the lottery now free prize",  # спам
    "Hi how are you doing today",      # не спам
    "Free subscription claim now",     # спам
    "Nice to meet you friend"          # не спам
]

vectorizer_example = CountVectorizer()
w = vectorizer_example.fit_transform(example_texts)

print(f"  Размер матрицы: {w.shape}  ← (4 сообщения, {w.shape[1]} уникальных слов)")
print(f"  Словарь (первые 10 слов): {list(vectorizer_example.vocabulary_.keys())[:10]}")
print("\n  Матрица (в плотном виде):")
print(pd.DataFrame(w.toarray(), columns=vectorizer_example.get_feature_names_out()))
# w[1000] — пример обращения к одному элементу разреженной матрицы
print(f"\n  w[0, 0] = {w[0, 0]}  ← значение в 1-й строке (нулевое слово)")

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 1.6 — РАЗБИВКА НА ОБУЧАЮЩУЮ И ТЕСТОВУЮ ВЫБОРКИ
# test_size=0.25 → 25% данных оставляем для проверки, 75% для обучения
# ────────────────────────────────────────────────────────────────────────────
from sklearn.model_selection import train_test_split

X_tr, X_tst, y_tr, y_tst = train_test_split(
    data["Message"],   # X — тексты сообщений (входные данные)
    data["Spam"],      # y — правильные ответы (0=ham, 1=spam)
    test_size=0.25     # 25% уйдёт на тест
)

print(f"\n Разбивка данных:")
print(f"  Обучающая выборка: {len(X_tr)} SMS")
print(f"  Тестовая выборка:  {len(X_tst)} SMS")

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 1.7 — НАИВНЫЙ БАЙЕС (MultinomialNB)
# ────────────────────────────────────────────────────────────────────────────
from sklearn.naive_bayes import MultinomialNB

# Почему Naive Bayes работает для текстов
# Теорема Байеса: P(спам|слова) = P(слова|спам) × P(спам) / P(слова)
# "Наивный" — предполагаем, что слова независимы друг от друга.
# Multinomial — работает с данными, которые представляют СЧЁТЧИКИ (как у нас: сколько раз слово).

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 1.8 — PIPELINE (конвейер, объединяющий vectorizer + модель)
# ────────────────────────────────────────────────────────────────────────────
from sklearn.pipeline import Pipeline

# Pipeline автоматически:
# 1. Сначала применяет CountVectorizer (строки → числовая матрица)
# 2. Затем обучает MultinomialNB на этой матрице
# Главный плюс: predict() принимает сразу тексты, без ручной векторизации!
md = Pipeline([
    ("vectorizer", CountVectorizer()),   # шаг 1: текст → мешок слов
    ("nb", MultinomialNB())              # шаг 2: наивный байес
])

# Обучение
md.fit(X_tr, y_tr)
print("\n Модель обучена (Pipeline: CountVectorizer + MultinomialNB)")

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 1.9 — ПРЕДСКАЗАНИЕ НА НОВЫХ ТЕКСТАХ
# ────────────────────────────────────────────────────────────────────────────
texts = [
    "Hi! How are you?",                          # ожидаем: 0 (ham)
    "Win the lottery",                            # ожидаем: 1 (spam)
    "Free subscription",                          # ожидаем: 1 (spam)
    "Black Friday big discount shop offer",       # ожидаем: 0 или 1 (спорно)
    "Nice to meet you"                            # ожидаем: 0 (ham)
]

predictions = md.predict(texts)
print("\n Предсказания для новых сообщений:")
for text, pred in zip(texts, predictions):
    label = "SPAM" if pred == 1 else "ham"
    print(f"  [{label}] {text[:50]}")

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 1.10 — ОЦЕНКА КАЧЕСТВА НА ТЕСТОВОЙ ВЫБОРКЕ
# ────────────────────────────────────────────────────────────────────────────
y_pred_spam = md.predict(X_tst)
acc = accuracy_score(y_tst, y_pred_spam)
print(f"\n Точность (accuracy) на тестовой выборке: {acc*100:.1f}%")
print(f"  precision: {precision_score(y_tst, y_pred_spam):.3f}")
print(f"  recall:    {recall_score(y_tst, y_pred_spam):.3f}")
print(f"  F1-мера:   {f1_score(y_tst, y_pred_spam):.3f}")


#  Вывод по Проекту 1:
#     Pipeline = удобный конвейер "сырые тексты → предсказание"
#     CountVectorizer + MultinomialNB — классическая связка для текстов
#     Accuracy ~97%+ — Naive Bayes отлично подходит для спам-фильтров
