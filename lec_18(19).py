section("ПРОЕКТ 2: ОБНАРУЖЕНИЕ ФИШИНГОВЫХ САЙТОВ")

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 2.1 — ЗАГРУЗКА ДАННЫХ
# ────────────────────────────────────────────────────────────────────────────
print("\n Загружаем phishing.csv...")
data_phish = pd.read_csv("phishing.csv", index_col=0)

print(data_phish.head())
print(f"\nФорма данных: {data_phish.shape}")

# Проверяем столбцы
print("\nСтолбцы:", data_phish.columns.tolist())

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 2.2 — РАЗДЕЛЕНИЕ НА X (признаки) и y (целевая переменная)
# ────────────────────────────────────────────────────────────────────────────
# В датасете столбец 'class' — это метка:
#   1 = легитимный сайт
#  -1 = фишинговый сайт

X_phish = data_phish.drop(columns=["class"])   # Все столбцы кроме class — это признаки
y_phish = data_phish["class"]                  # Целевая переменная — class

print(f"\n X (признаки): {X_phish.shape}")
print(f"   y (метки):     {y_phish.value_counts().to_dict()}")
print(f"     1 = легитимный сайт")
print(f"    -1 = фишинговый сайт")

print(f"\nПервые 3 строки признаков:")
print(X_phish.head(3).to_string())

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 2.3 — РАЗБИВКА НА TRAIN / TEST
# ────────────────────────────────────────────────────────────────────────────
from sklearn.model_selection import train_test_split

X_tr_p, X_tst_p, y_tr_p, y_tst_p = train_test_split(
    X_phish, y_phish, test_size=0.25
)

print(f"\n Обучающая выборка: {len(X_tr_p)} сайтов")
print(f"   Тестовая выборка:  {len(X_tst_p)} сайтов")

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 2.4 — ДЕРЕВО РЕШЕНИЙ
# ────────────────────────────────────────────────────────────────────────────
from sklearn.tree import DecisionTreeClassifier

dt = DecisionTreeClassifier()        # Создаём классификатор
model_phish = dt.fit(X_tr_p, y_tr_p) # Обучаем: fit(X, y)

predict_phish = model_phish.predict(X_tst_p)

print(f"\n DecisionTreeClassifier обучен")
print(f"   Точность (accuracy): {accuracy_score(predict_phish, y_tst_p)*100:.1f}%")

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 2.5 — ТЕОРИЯ: ТИПЫ КЛАССИФИКАЦИИ
# ────────────────────────────────────────────────────────────────────────────

# ТИПЫ ЗАДАЧ КЛАССИФИКАЦИИ:
#  1. Бинарная (двоичная) классификация:
#     Два класса: 0 или 1, спам или нет, фишинг или нет.
#     Наш проект с фишингом — именно этот тип.
#
#  2. Мультиклассовая классификация:
#     Три и более класса: вид ириса (setosa/versicolor/virginica),
#     цифра на фото (0, 1, 2, ..., 9).
#
#  3. Многометочная (многоклассовая-одновременная):
#     Один объект может принадлежать НЕСКОЛЬКИМ классам одновременно.
#     Пример: статья может быть одновременно про «технологии» И «политику».


# ────────────────────────────────────────────────────────────────────────────
# ШАГ 2.6 — МАТРИЦА ОШИБОК И ТИПЫ ОШИБОК
# ────────────────────────────────────────────────────────────────────────────
#МАТРИЦА ОШИБОК (Confusion Matrix) и ТИПЫ ОШИБОК:
#
#  ┌──────────────────┬────────────────────┬───────────────────┐
#  │                  │  Предсказано:  1   │  Предсказано: -1  │
#  ├──────────────────┼────────────────────┼───────────────────┤
#  │  Фактически:  1  │  TP (True  Pos)    │  FN (False Neg)   │
#  │                  │  Правильный +      │  Пропустили +     │
#  ├──────────────────┼────────────────────┼───────────────────┤
#  │  Фактически: -1  │  FP (False Pos)    │  TN (True  Neg)   │
#  │                  │  Ложная тревога    │  Правильный −     │
#  └──────────────────┴────────────────────┴───────────────────┘
#
#  FP = Ложноположительное: модель сказала "фишинг", а сайт — нормальный.
#       "Волк-волк, а волка нет" — ложная тревога.
#  FN = Ложноотрицательное: модель сказала "нормальный", а это фишинг
#       Пропустили мошенника — самая опасная ошибка.

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 2.7 — МЕТРИКИ КАЧЕСТВА (ключевой теоретический блок лекции)
# ────────────────────────────────────────────────────────────────────────────
# МЕТРИКИ КАЧЕСТВА БИНАРНОГО КЛАССИФИКАТОРА:
#  ─────────────────────────────────────────────────────────────
#  Accuracy (Точность ответов) = (TP + TN) / (TP + TN + FP + FN)
#    «Процент правильных ответов» — универсальная, но обманчивая метрика.
#    Если 99% данных — один класс, accuracy=99% при пустой модели
#
#  ─────────────────────────────────────────────────────────────
#  Precision (Точность, Положительная предсказательная ценность):
#    = TP / (TP + FP)
#    Важна, когда СТОИМОСТЬ ЛОЖНОГО СРАБАТЫВАНИЯ высока
#    Пример: спам-фильтр — нельзя пропустить важное письмо в спам
#
#  ─────────────────────────────────────────────────────────────
#  Recall (Полнота, Чувствительность, Sensitivity):
#    = TP / (TP + FN)
#    Важна, когда СТОИМОСТЬ ПРОПУСКА высока.
#    Пример: рак, мошенничество — нельзя пропустить больного/мошенника
#
#  ─────────────────────────────────────────────────────────────
#  Specificity (Специфичность):
#    = TN / (TN + FP)
#    = Полнота, но для отрицательного класса (recall с pos_label=0).
#
#  ─────────────────────────────────────────────────────────────
#  F1-мера = 2 × (Precision × Recall) / (Precision + Recall)
#    Гармоническое среднее precision и recall.
#    Лучшая единая метрика, когда важны ОБА показателя.
#    Если Precision = 1 и Recall = 0 → F1 = 0 (не обманывает).
# ─────────────────────────────────────────────────────────────
#
#  КОМПРОМИСС PRECISION vs RECALL:
#    Повышая порог уверенности → Precision↑, Recall↓
#    Снижая порог              → Precision↓, Recall↑
#    Нельзя одновременно максимизировать оба — нужен баланс.


# ────────────────────────────────────────────────────────────────────────────
# ШАГ 2.8 — ВЫЧИСЛЕНИЕ ВСЕХ МЕТРИК ДЛЯ МОДЕЛИ ФИШИНГА
# ────────────────────────────────────────────────────────────────────────────
print("Метрики для DecisionTree на задаче обнаружения фишинга:")

# Точность (accuracy) — процент правильных ответов
acc_p = accuracy_score(predict_phish, y_tst_p)

# Precision — из всех "фишинговых" предсказаний, сколько правда фишинговых?
prec_p = precision_score(y_tst_p, predict_phish, pos_label=-1)

# Recall (чувствительность) — из всех реальных фишингов сколько 
rec_p = recall_score(y_tst_p, predict_phish, pos_label=-1)

# Специфичность — recall, но для "легитимных" (pos_label=1)
spec_p = recall_score(y_tst_p, predict_phish, pos_label=1)

# F1-мера — баланс между precision и recall
f1_p = f1_score(y_tst_p, predict_phish, pos_label=-1)

print(f"  Accuracy (точность ответов):   {acc_p*100:.1f}%")
print(f"  Precision (точность):          {prec_p:.3f}")
print(f"  Recall / Sensitivity (полнота):{rec_p:.3f}")
print(f"  Specificity (специфичность):   {spec_p:.3f}")
print(f"  F1-мера:                       {f1_p:.3f}")

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 2.9 — ВИЗУАЛИЗАЦИЯ МАТРИЦЫ ОШИБОК
# ────────────────────────────────────────────────────────────────────────────
fig, ax = plt.subplots(figsize=(6, 5))
disp = ConfusionMatrixDisplay.from_estimator(
    model_phish,
    X_tst_p,
    y_tst_p,
    display_labels=["Фишинговый (-1)", "Легитимный (1)"],
    cmap='Blues',
    ax=ax
)
ax.set_title("Матрица ошибок: Обнаружение фишинга\n"
             "Строки = реальный класс, Столбцы = предсказанный", fontsize=12)
plt.tight_layout()
plt.show()

print("""
     Как читать матрицу:
     Главная диагональ — правильные ответы
     Вне диагонали — ошибки:
       Верхний правый = FN: пропустили фишинг (опасно)
       Нижний левый   = FP: ложная тревога (помеха)
""")

