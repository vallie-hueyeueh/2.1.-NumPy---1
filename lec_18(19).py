section("ПРОЕКТ 3: ОБНАРУЖЕНИЕ МОШЕННИЧЕСТВА С БАНКОВСКИМИ КАРТАМИ")

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 3.1 — ЗАГРУЗКА ДАННЫХ
# ────────────────────────────────────────────────────────────────────────────
# Датасет с Kaggle "Credit Card Fraud Detection"
# Содержит транзакции европейских держателей карт за сентябрь 2013 года
# Признаки V1-V28 — результат PCA-преобразования реальных данных (анонимизация)
# Class: 0 = легитимная транзакция, 1 = мошенническая

print("\n creditcard.csv...")
data_cc = pd.read_csv("creditcard.csv")
print(data_cc.head())

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 3.2 — АНАЛИЗ НЕСБАЛАНСИРОВАННОСТИ КЛАССОВ
# ────────────────────────────────────────────────────────────────────────────
legit = data_cc[data_cc["Class"] == 0]   # Легитимные транзакции
fraud = data_cc[data_cc["Class"] == 1]   # Мошеннические транзакции

print(f"\n Распределение классов (СИЛЬНО несбалансированное):")
print(f"  Легитимных:     {len(legit):7d} ({len(legit)/len(data_cc)*100:.2f}%)")
print(f"  Мошеннических:  {len(fraud):7d} ({len(fraud)/len(data_cc)*100:.2f}%)")

print("""
   ПРОБЛЕМА НЕСБАЛАНСИРОВАННЫХ КЛАССОВ:
    Если мошенничество = 0.17% всех транзакций, то
    «тупая» модель, всегда говорящая «легитимная»,
    получит accuracy = 99.83% — но не поймает НИ ОДНОГО мошенника
    
    Именно поэтому для таких задач используют:
     ✔ Матрицу ошибок (видим реальную картину)
     ✔ Precision и Recall (честные метрики)
     ✔ F1-мера (баланс между ними)
     ✗ Accuracy — БЕСПОЛЕЗНА при несбалансированных классах
""")

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 3.3 — ПОДГОТОВКА X и y
# ────────────────────────────────────────────────────────────────────────────
# Убираем "Time" (не несёт полезной информации) и "Class" (целевая переменная)
X_cc = data_cc.drop(["Time", "Class"], axis=1)
y_cc = data_cc["Class"]

print(f" Признаки X: {X_cc.shape}  (столбцы: {X_cc.columns.tolist()[:5]}...)")
print(f"  Целевая y:  {y_cc.shape}")

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 3.4 — РАЗБИВКА НА TRAIN / TEST
# ────────────────────────────────────────────────────────────────────────────
X_tr_cc, X_tst_cc, y_tr_cc, y_tst_cc = train_test_split(
    X_cc, y_cc, test_size=0.25
)

print(f"\n Обучающая выборка: {len(X_tr_cc):6d} транзакций")
print(f"   Тестовая выборка:  {len(X_tst_cc):6d} транзакций")

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 3.5 — МОДЕЛЬ 1: ЛОГИСТИЧЕСКАЯ РЕГРЕССИЯ
# ────────────────────────────────────────────────────────────────────────────
from sklearn.linear_model import LogisticRegression

print("\n Обучаем Logistic Regression...")
print("  (max_iter=1000 чтобы избежать ConvergenceWarning)")

# «STOP: TOTAL NO. OF ITERATIONS REACHED LIMIT» — модель не сошлась
# Решение: увеличить max_iter (количество итераций оптимизатора)
modell = LogisticRegression(max_iter=1000)  # По умолчанию max_iter=100 — мало
modell.fit(X_tr_cc, y_tr_cc)
print(" LogisticRegression обучена")

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 3.6 — МАТРИЦА ОШИБОК ДЛЯ LOGISTIC REGRESSION
# ConfusionMatrixDisplay.from_estimator() — удобный способ построить матрицу
# сразу из обученной модели (не нужно отдельно делать predict)
# ────────────────────────────────────────────────────────────────────────────
print("\n Строим матрицу ошибок для Logistic Regression...")

fig, ax = plt.subplots(figsize=(7, 6))
ConfusionMatrixDisplay.from_estimator(
    modell,                                              # Обученная модель
    X_tst_cc,                                           # Тестовые признаки
    y_tst_cc,                                           # Правильные ответы
    display_labels=["Легитимная", "Мошенническая"],     # Подписи классов
    cmap='viridis',                                      # Цветовая схема
    ax=ax
)
ax.set_title(
    "Матрица ошибок: Logistic Regression\nDetection Credit Card Fraud",
    fontsize=12, fontweight='bold'
)
plt.tight_layout()
plt.show()

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 3.7 — ТОЧНОСТЬ И ПОЛНОТА ДЛЯ LOGISTIC REGRESSION
# ────────────────────────────────────────────────────────────────────────────
y_pred_lr = modell.predict(X_tst_cc)

print("\n Метрики Logistic Regression (мошеннические транзакции = класс 1):")
print(f"  Accuracy:   {accuracy_score(y_tst_cc, y_pred_lr)*100:.1f}%  ← бесполезна здесь")
print(f"  Precision:  {precision_score(y_tst_cc, y_pred_lr):.3f}  ← из предсказанных мошенников, сколько правда")
print(f"  Recall:     {recall_score(y_tst_cc, y_pred_lr):.3f}  ← из реальных мошенников, скольких нашли")
print(f"  Specificity:{recall_score(y_tst_cc, y_pred_lr, pos_label=0):.3f}  ← recall для легитимных")
print(f"  F1-мера:    {f1_score(y_tst_cc, y_pred_lr):.3f}  ← баланс precision и recall")

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 3.8 — МОДЕЛЬ 2: RANDOM FOREST
# Random Forest для сравнения
# ────────────────────────────────────────────────────────────────────────────
from sklearn.ensemble import RandomForestClassifier

print("\n Обучаем Random Forest (n_estimators=10 для скорости)...")
model2 = RandomForestClassifier(n_estimators=10, random_state=42)
model2.fit(X_tr_cc, y_tr_cc)
print(" RandomForestClassifier обучен")

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 3.9 — МАТРИЦА ОШИБОК ДЛЯ RANDOM FOREST
# ────────────────────────────────────────────────────────────────────────────
fig, ax = plt.subplots(figsize=(7, 6))
ConfusionMatrixDisplay.from_estimator(
    model2,
    X_tst_cc,
    y_tst_cc,
    display_labels=["Легитимная", "Мошенническая"],
    cmap='viridis',
    ax=ax
)
ax.set_title(
    "Матрица ошибок: Random Forest\nDetection Credit Card Fraud",
    fontsize=12, fontweight='bold'
)
plt.tight_layout()
plt.show()

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 3.10 — СРАВНЕНИЕ МОДЕЛЕЙ
# ────────────────────────────────────────────────────────────────────────────
y_pred_rf = model2.predict(X_tst_cc)

print("\n Метрики Random Forest:")
print(f"  Accuracy:   {accuracy_score(y_tst_cc, y_pred_rf)*100:.1f}%")
print(f"  Precision:  {precision_score(y_tst_cc, y_pred_rf):.3f}")
print(f"  Recall:     {recall_score(y_tst_cc, y_pred_rf):.3f}")
print(f"  Specificity:{recall_score(y_tst_cc, y_pred_rf, pos_label=0):.3f}")
print(f"  F1-мера:    {f1_score(y_tst_cc, y_pred_rf):.3f}")

# ────────────────────────────────────────────────────────────────────────────
# ИТОГОВОЕ СРАВНЕНИЕ ОБЕИХ МОДЕЛЕЙ
# ────────────────────────────────────────────────────────────────────────────
print("\n ИТОГОВОЕ СРАВНЕНИЕ МОДЕЛЕЙ:")
print(f"{'Метрика':<18} {'Logistic Reg':>14} {'Random Forest':>14}")
print("─" * 48)
metrics_names  = ['Precision', 'Recall', 'Specificity', 'F1-мера']
lr_scores  = [precision_score(y_tst_cc, y_pred_lr),
              recall_score(y_tst_cc, y_pred_lr),
              recall_score(y_tst_cc, y_pred_lr, pos_label=0),
              f1_score(y_tst_cc, y_pred_lr)]
rf_scores  = [precision_score(y_tst_cc, y_pred_rf),
              recall_score(y_tst_cc, y_pred_rf),
              recall_score(y_tst_cc, y_pred_rf, pos_label=0),
              f1_score(y_tst_cc, y_pred_rf)]
for name, lr, rf in zip(metrics_names, lr_scores, rf_scores):
    better = '← RF лучше' if rf > lr else ('← LR лучше' if lr > rf else '')
    print(f"  {name:<16} {lr:>13.3f} {rf:>13.3f}  {better}")

# ────────────────────────────────────────────────────────────────────────────
# ШАГ 3.11 — ВИЗУАЛИЗАЦИЯ: СРАВНЕНИЕ ДВУХ МАТРИЦ РЯДОМ
# ────────────────────────────────────────────────────────────────────────────
fig, axes = plt.subplots(1, 2, figsize=(14, 6))
fig.suptitle("Сравнение: Logistic Regression vs Random Forest\n"
             "Credit Card Fraud Detection", fontsize=14, fontweight='bold')

for ax_i, model_i, title_i in [
    (axes[0], modell,  "Logistic Regression"),
    (axes[1], model2,  "Random Forest"),
]:
    ConfusionMatrixDisplay.from_estimator(
        model_i, X_tst_cc, y_tst_cc,
        display_labels=["Легитимная", "Мошенническая"],
        cmap='Blues', ax=ax_i
    )
    ax_i.set_title(title_i, fontsize=12)

plt.tight_layout()
plt.show()

print("""
     Вывод по Проекту 3:
     При несбалансированных классах accuracy — не информативна.
     Смотрим на Recall для мошенников: сколько пропустили
     F1-мера показывает итоговый баланс качества.
     Random Forest обычно лучше Logistic Regression на таких задачах.
""")


